@pytest.fixture(autouse=True)
def _free_the_worlds():
    """Collect after every test. A World refers to itself through its
    particle solver (`matter.w`), so a world a test leaves behind is freed
    only by a cycle collection, and Python runs the full one rarely. A run
    of the sound tests climbed to 2.6 GB that way and the OOM killer took
    the user's editor (2026-10-09). A collection costs milliseconds."""
    yield
    gc.collect()


def pytest_configure(config):
    config.addinivalue_line(
        "markers", "slow: not run by FAST (tools/golden.py 4.2); still runs by node id")


def _undefined(slow):
    """SLOW keys whose file has no such test function. Read from the source,
    not from what was collected: a run of one file or one node id collects
    only part of the suite, and every slow test outside it is not missing."""
    here = os.path.dirname(__file__)
    found = {}
    bad = []
    for key in sorted(slow):
        fname, test = key.split("::")
        if fname not in found:
            path = os.path.join(here, fname)
            found[fname] = open(path).read() if os.path.exists(path) else ""
        if not re.search(rf"^def {re.escape(test)}\(", found[fname], re.M):
            bad.append(key)
    return bad


def pytest_collection_modifyitems(config, items):
    missing = _undefined(SLOW)
    if missing:
        raise pytest.UsageError(
            f"tests/conftest.py: SLOW names a test that does not exist: {missing}")
    for item in items:
        name = getattr(item, "originalname", None) or item.name.split("[")[0]
        if f"{item.path.name}::{name}" in SLOW:
            item.add_marker(pytest.mark.slow)
